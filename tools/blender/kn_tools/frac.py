"""Fracture export (ASSET_PIPELINE §7, M2 stream E1): FRAC__<n> chunks -> <type>.frac.glb + a parts-data module.

`<type>.frac.glb`: one root node per chunk, named FRAC__NN in chunk order, each placed in part space at its own
centre of mass (node translation; mesh vertices relative to it), single LOD, master ids as material names.
`packages/parts-data/src/frac_<type>.ts`: generated literals for the sim (D66: chunk bodies exist dormant from
the start): per chunk its name, centre of mass, volume, mass share (volume fraction of all chunks) and a convex
hull of at most MAX_HULL points, all in engine metres (Y-up, part space). The hull points are a subset of the
chunk's own vertices (farthest-point sampled from its convex hull), so tests can match them to the glb.
"""
import json
import os

import bmesh
import bpy
from mathutils import Matrix, Vector

from . import validate
from .conventions import blender_to_engine, round_list

MAX_HULL = 32


class FracError(RuntimeError):
    pass


def chunks(scene):
    obs = [ob for ob in validate.collection_objects(scene, 'FRAC') if ob.type == 'MESH']
    out = []
    for ob in obs:
        tail = ob.name.split('__', 1)[-1]
        if not tail.isdigit():
            raise FracError('%s: FRAC objects are named FRAC__<n>' % ob.name)
        out.append((int(tail), ob))
    out.sort(key=lambda t: t[0])
    return [ob for _n, ob in out]


def _bm(ob, dg):
    bm = bmesh.new()
    bm.from_object(ob, dg)
    bm.transform(ob.matrix_world)
    bmesh.ops.triangulate(bm, faces=bm.faces)
    return bm


def mass_props(bm):
    """Volume and centroid of a closed triangulated mesh (signed tetrahedra about the origin)."""
    vol = 0.0
    c = Vector((0.0, 0.0, 0.0))
    for f in bm.faces:
        a, b, d = (v.co for v in f.verts)
        v6 = a.dot(b.cross(d))
        vol += v6
        c += (a + b + d) * v6
    if abs(vol) < 1e-12:
        raise FracError('chunk has no volume (not closed?)')
    return abs(vol) / 6.0, c / (4.0 * vol)


def hull_points(bm, limit=MAX_HULL):
    """Convex hull vertices of the chunk, farthest-point sampled down to `limit` (a subset of its vertices)."""
    tmp = bmesh.new()
    vs = [tmp.verts.new(v.co) for v in bm.verts]
    res = bmesh.ops.convex_hull(tmp, input=vs, use_existing_faces=False)
    used = {v for f in res['geom'] if isinstance(f, bmesh.types.BMFace) for v in f.verts}
    pts = [v.co.copy() for v in used]
    tmp.free()
    if len(pts) <= limit:
        return pts
    cen = sum(pts, Vector()) / len(pts)
    pick = [max(pts, key=lambda p: (p - cen).length)]
    dmin = [(p - pick[0]).length for p in pts]
    while len(pick) < limit:
        i = max(range(len(pts)), key=lambda k: dmin[k])
        pick.append(pts[i])
        dmin = [min(dmin[k], (pts[k] - pts[i]).length) for k in range(len(pts))]
    return pick


def export_frac_glb(scene, obs, centres, filepath):
    created = []
    try:
        for ob in scene.objects:
            ob.select_set(False)
        for ob, c in zip(obs, centres):
            dg = bpy.context.evaluated_depsgraph_get()
            me = bpy.data.meshes.new_from_object(ob.evaluated_get(dg))
            me.transform(ob.matrix_world)
            me.transform(Matrix.Translation(-c))
            nob = bpy.data.objects.new(ob.name + '_x', me)
            scene.collection.objects.link(nob)
            nob.location = c
            created.append((nob, ob.name))
        for nob, name in created:  # take the FRAC__NN names for the export copies
            src = bpy.data.objects.get(name)
            if src is not None:
                src.name = name + '_src'
            nob.name = name
            nob.select_set(True)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        bpy.ops.export_scene.gltf(
            filepath=filepath, export_format='GLB', use_selection=True, export_apply=False, export_yup=True,
            export_cameras=False, export_lights=False, export_extras=False, export_animations=False,
            export_materials='EXPORT', export_image_format='NONE', export_texcoords=True, export_normals=True,
            export_tangents=False, export_draco_mesh_compression_enable=False, export_skins=False,
            export_morph=False)
    finally:
        for nob, name in created:
            me = nob.data
            bpy.data.objects.remove(nob)
            bpy.data.meshes.remove(me)
            src = bpy.data.objects.get(name + '_src')
            if src is not None:
                src.name = name
    return filepath


def _num(x):
    s = repr(round(float(x), 6) + 0.0)
    return s[:-2] if s.endswith('.0') else s


def _v(v):
    return '[' + ', '.join(_num(x) for x in v) + ']'


def ts_module(ptype, entries, source):
    const = ptype.upper() + '_FRAC'
    lines = [
        '// GENERATED by tools/blender/export_frac.py from %s; do not edit (node tools/assets.mjs %s --frac).' % (
            source, ptype),
        '// Fracture chunks of %s (ASSET_PIPELINE §7; D66: the sim pre-creates them as dormant bodies). Engine metres,' %
        ptype.upper().replace('_', ' '),
        '// Y-up, part space. centre = chunk centre of mass (its node translation in %s.frac.glb); hull = convex hull'
        % ptype,
        '// points (<= %d, a subset of the chunk vertices); massShare = chunk volume / all chunks (sums to 1).' %
        MAX_HULL,
        'export const %s: {' % const,
        '  readonly type: string;',
        '  readonly glb: string;',
        '  readonly chunks: readonly {',
        '    readonly name: string; readonly centre: readonly [number, number, number]; readonly volume: number;',
        '    readonly massShare: number; readonly hull: readonly (readonly [number, number, number])[];',
        '  }[];',
        '} = {',
        "  type: '%s'," % ptype,
        "  glb: 'parts/%s/%s.frac.glb'," % (ptype, ptype),
        '  chunks: [',
    ]
    for e in entries:
        lines.append("    { name: '%s', centre: %s, volume: %s, massShare: %s, hull: [" % (
            e['name'], _v(e['centre']), _num(e['volume'] * 1e6) + 'e-6', _num(e['massShare'])))
        hull = e['hull']
        for i in range(0, len(hull), 4):
            lines.append('      ' + ', '.join(_v(p) for p in hull[i:i + 4]) + ',')
        lines.append('    ] },')
    lines += ['  ],', '};', '']
    return '\n'.join(lines)


def export_frac(scene, out_dir, ts_path, ptype, source='', log=print):
    obs = chunks(scene)
    if not obs:
        raise FracError('%s has no FRAC__<n> chunks' % ptype)
    dg = bpy.context.evaluated_depsgraph_get()
    entries, centres = [], []
    for ob in obs:
        bm = _bm(ob, dg)
        vol, c = mass_props(bm)
        hull = hull_points(bm)
        bm.free()
        centres.append(c)
        entries.append({'name': ob.name, 'volume': vol, 'centre': round_list(blender_to_engine(c), 6),
                        'hull': [round_list(blender_to_engine(p), 6) for p in hull]})
    total = sum(e['volume'] for e in entries)
    for e in entries:
        e['massShare'] = e['volume'] / total
    glb = export_frac_glb(scene, obs, centres, os.path.join(out_dir, ptype + '.frac.glb'))
    os.makedirs(os.path.dirname(ts_path), exist_ok=True)
    with open(ts_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(ts_module(ptype, entries, source))
    summary = {'type': ptype, 'chunks': len(entries), 'glb': glb, 'ts': ts_path,
               'hullPoints': [len(e['hull']) for e in entries], 'volume': total}
    with open(os.path.join(out_dir, ptype + '.frac.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(summary, f, indent=1)
        f.write('\n')
    log('frac %s: %d chunks -> %s, %s (hull points %s)' % (ptype, len(entries), glb, ts_path,
                                                            '/'.join(str(n) for n in summary['hullPoints'])))
    return summary
