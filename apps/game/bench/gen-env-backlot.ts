// Generates packages/parts-data/src/env_backlot.ts (literals only, determinism lint) from E3b's
// assets/build/env/backlot/backlot.json: the Backlot dressing's static colliders for the Arena and Megastructure lots.
//   node --disable-warning=ExperimentalWarning apps/game/bench/gen-env-backlot.ts
//
// J4 (M4): Megastructure. E3b placed the dressing on the Arena lot ("Arena = Mega origin"), each piece at the lowest
// ground over its footprint. The Megastructure lot is taller (default ground 16 m, not 4 m) and has its own swells,
// so each placement is lifted by (lowest Mega ground − lowest Arena ground) over the same footprint (its boxes' x/z
// bounds, sampled on a ≤ 0.25 m grid) — the pieces keep exactly the footing they have on the Arena lot. On the
// flat pads (water tower, light towers, trailers) that is the pad height difference. Soundstages have no boxes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defaultTerrain, terrainHeightAt, type TerrainRecord } from '@knockon/format';

const root = fileURLToPath(new URL('../../../', import.meta.url));
interface Box { center: number[]; half: number[]; phys: string }
const j = JSON.parse(readFileSync(`${root}assets/build/env/backlot/backlot.json`, 'utf8')) as { dressing: { placements: { piece: string; backdropArena: boolean; boxes: Box[] }[] } };
const r = (v: number): number => Math.round(v * 1e4) / 1e4;
const arenaLot = defaultTerrain('arena')!, megaLot = defaultTerrain('megastructure')!;

/** Lowest ground of `t` over the x/z bounds of `boxes`. */
function lowest(t: TerrainRecord, boxes: readonly Box[]): number {
  let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity;
  for (const b of boxes) {
    x0 = Math.min(x0, b.center[0]! - b.half[0]!); x1 = Math.max(x1, b.center[0]! + b.half[0]!);
    z0 = Math.min(z0, b.center[2]! - b.half[2]!); z1 = Math.max(z1, b.center[2]! + b.half[2]!);
  }
  const nx = Math.max(1, Math.ceil((x1 - x0) / 0.25)), nz = Math.max(1, Math.ceil((z1 - z0) / 0.25));
  let m = Infinity;
  for (let a = 0; a <= nx; a++) for (let c = 0; c <= nz; c++) m = Math.min(m, terrainHeightAt(t, x0 + ((x1 - x0) * a) / nx, z0 + ((z1 - z0) * c) / nz));
  return m;
}

const arena: string[] = [], mega: string[] = [], lifts: string[] = [];
let n = 0;
j.dressing.placements.forEach((p, i) => {
  if (p.backdropArena || !p.boxes.length) return;
  const lift = r(lowest(megaLot, p.boxes) - lowest(arenaLot, p.boxes));
  lifts.push(`[${i}, ${lift}]`);
  for (const b of p.boxes) {
    const name = `${p.piece}_${n++}`;
    arena.push(`    { name: '${name}', center: [${b.center.map(r).join(', ')}], half: [${b.half.map(r).join(', ')}], phys: '${b.phys}' },`);
    mega.push(`    { name: '${name}', center: [${r(b.center[0]!)}, ${r(b.center[1]! + lift)}, ${r(b.center[2]!)}], half: [${b.half.map(r).join(', ')}], phys: '${b.phys}' },`);
  }
});
const out = `// GENERATED by apps/game/bench/gen-env-backlot.ts from assets/build/env/backlot/backlot.json (E3b). Do not edit by hand.
// THE BACKLOT dressing colliders (environments.md §4.3): static boxes in engine metres on the default ground (the pads
// under the water tower, light towers and trailers are flattened in format terrain.ts). The sim builds them as one
// static set per physics material (Machine.buildSet). Literals only (determinism lint).
// Arena: E3b's placements as exported. Megastructure (J4, M4): the same placements, each lifted by its footprint's
// lowest Mega ground minus its lowest Arena ground (\`megaLift\`: [placement index in backlot.json, metres]), so the
// renderer can seat the dressing art the same way.
// ${n} boxes from ${lifts.length} placements.

export type BacklotPhys = 'powder' | 'wood' | 'ceramic' | 'steel' | 'glass' | 'rubber' | 'paper' | 'fabric';
export interface BacklotBox { readonly name: string; readonly center: readonly [number, number, number]; readonly half: readonly [number, number, number]; readonly phys: BacklotPhys }
export interface BacklotSet { readonly boxes: readonly BacklotBox[]; readonly spheres: readonly never[] }

export const BACKLOT: { readonly arena: BacklotSet; readonly megastructure: BacklotSet; readonly megaLift: readonly (readonly [number, number])[] } = {
  arena: {
    boxes: [
${arena.join('\n')}
    ],
    spheres: [],
  },
  megastructure: {
    boxes: [
${mega.join('\n')}
    ],
    spheres: [],
  },
  megaLift: [${lifts.join(', ')}],
};
`;
writeFileSync(`${root}packages/parts-data/src/env_backlot.ts`, out);
console.log(`env_backlot.ts: ${n} boxes per lot, ${lifts.length} placements; Mega lift ${Math.min(...lifts.map((s) => Number(s.split(', ')[1]!.slice(0, -1)))).toFixed(2)}–${Math.max(...lifts.map((s) => Number(s.split(', ')[1]!.slice(0, -1)))).toFixed(2)} m`);
