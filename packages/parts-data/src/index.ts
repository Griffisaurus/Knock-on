/** Single-collider summary of a part (art-pipeline cross-checks, quick tools). */
export interface BlockoutDef {
  readonly type: string;
  readonly name: string;
  readonly tag: string;
  readonly shape: 'box' | 'sphere';
  readonly size: readonly [number, number, number];
  readonly motion: 'static' | 'dynamic';
  readonly mass: number;
  readonly friction: number;
  readonly restitution: number;
  readonly ccd: boolean;
}

export function blockout(type: string): BlockoutDef | undefined {
  const d = partDef(type);
  if (!d) return undefined;
  const s = d.shapes({})[0];
  const size = d.bounds.max.map((v, i) => v - d.bounds.min[i]!) as [number, number, number];
  return {
    type: d.type, name: d.name, tag: d.tag, shape: s?.kind === 'sphere' ? 'sphere' : 'box', size,
    motion: d.body.kind, mass: d.body.mass, friction: d.body.friction, restitution: d.body.restitution, ccd: d.body.ccd ?? false,
  };
}

